import { readFileSync, writeFileSync, chmodSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
// Windows source checkouts may use CRLF. Generated Bash still uses LF, and
// consistency compares source text independently of checkout conversion.
const read = name => readFileSync(resolve(root, 'scripts/release', name), 'utf8').replaceAll('\r\n', '\n');
const catalog = JSON.parse(read('launcher-messages.json'));
const quote = value => `'${value.replaceAll("'", "'\\''")}'`;
const messages = Object.entries(catalog).flatMap(([id, entry]) => {
  if (Object.keys(entry).sort().join(',') !== 'en,ru') throw new Error(`Catalog parity: ${id}`);
  const placeholders = value => [...value.matchAll(/\{([A-Za-z]+)\}/gu)].map(match => match[1]).sort().join(',');
  if (placeholders(entry.en) !== placeholders(entry.ru)) throw new Error(`Placeholder parity: ${id}`);
  return [`    ${id}:en) printf '%s' ${quote(entry.en)};;`, `    ${id}:ru) printf '%s' ${quote(entry.ru)};;`];
}).join('\n');
const presenter = `ore_message() {\n  case "$1:$ore_language" in\n${messages}\n    *) return 1;;\n  esac\n}\n`;
const shared = presenter + read('macos-helper.sh') + '\n' + read('load-env.sh') + '\n' + read('snapshot-input.sh') + '\n' + read('private-runtime.sh') + '\n' + read('macos-launcher-body.sh');
for (const [name, mode] of [['ORE-launcher.command', 'standalone'], ['scripts/release/macos-launcher.sh', 'installed']]) {
  const path = resolve(root, name);
  const output = `#!/bin/bash\n# Generated by scripts/release/generate-macos-launcher.mjs; edit its sources.\nore_entry_mode=${mode}\n${shared}`;
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8').replaceAll('\r\n', '\n') !== output) throw new Error(`Regenerate ${name}`);
  } else { writeFileSync(path, output, { mode: 0o755 }); chmodSync(path, 0o755); }
}
const internalPath = resolve(root, 'scripts/release/start.command');
const internalSource = readFileSync(internalPath, 'utf8').replaceAll('\r\n', '\n');
const internalBlock = /# BEGIN GENERATED MACOS HELPERS\n[\s\S]*?# END GENERATED MACOS HELPERS/u;
if (!internalBlock.test(internalSource)) throw new Error('Missing internal helper generation markers.');
const internalOutput = internalSource.replace(internalBlock,
  () => `# BEGIN GENERATED MACOS HELPERS\n${presenter}${read('macos-helper.sh')}# END GENERATED MACOS HELPERS`);
if (process.argv.includes('--check')) {
  if (internalSource !== internalOutput) throw new Error('Regenerate scripts/release/start.command');
} else writeFileSync(internalPath, internalOutput);
