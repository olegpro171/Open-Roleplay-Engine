import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const read = name => readFileSync(resolve(root, 'scripts/release', name), 'utf8').replaceAll('\r\n', '\n');
const quote = value => `'${value.replaceAll("'", "''")}'`;
const catalog = JSON.parse(read('launcher-messages.json'));
const entries = Object.entries(catalog).map(([id, entry]) => {
  if (Object.keys(entry).sort().join(',') !== 'en,ru') throw new Error(`Catalog parity: ${id}`);
  const parameters = value => [...value.matchAll(/\{([A-Za-z]+)\}/gu)].map(match => match[1]).sort().join(',');
  if (parameters(entry.en) !== parameters(entry.ru)) throw new Error(`Placeholder parity: ${id}`);
  return { id, assignment: `    ${quote(id)} = @{en=${quote(entry.en)};ru=${quote(entry.ru)}}` };
});
// cmd sees only ASCII. File path travels through an environment value with
// delayed expansion disabled and is never interpolated into PowerShell code.
const batch = `@echo off\r\nsetlocal DisableDelayedExpansion\r\nset "ORE_BOOTSTRAP_FILE=%~f0"\r\nset "ORE_BOOTSTRAP_PS=%SystemRoot%\\System32\\WindowsPowerShell\\v1.0\\powershell.exe"\r\nif exist "%SystemRoot%\\Sysnative\\WindowsPowerShell\\v1.0\\powershell.exe" set "ORE_BOOTSTRAP_PS=%SystemRoot%\\Sysnative\\WindowsPowerShell\\v1.0\\powershell.exe"\r\n"%ORE_BOOTSTRAP_PS%" -NoProfile -ExecutionPolicy RemoteSigned -Command "$s=[IO.File]::ReadAllText($env:ORE_BOOTSTRAP_FILE,[Text.Encoding]::UTF8);$m='# ORE_POWERSHELL_PAYLOAD';$i=$s.LastIndexOf($m); & ([scriptblock]::Create($s.Substring($i+$m.Length)))"\r\nexit /b %errorlevel%\r\n# ORE_POWERSHELL_PAYLOAD\r\n`;
const sources = names => names.map(read).join('\n');
const messages = entries => `$OreMessages = @{\n${entries.map(entry => entry.assignment).join('\n')}\n}\n`;
const shared = sources(['windows-common.ps1', 'windows-snapshot.ps1', 'windows-standalone-common.ps1', 'windows-package-lock.ps1', 'windows-package.ps1', 'windows-package-session.ps1']);
const generated = '# Generated by generate-windows-launcher.mjs; edit its sources.\n';
const bootstrapMessages = new Set([
  'heading', 'unsupportedSystem', 'folderCollision', 'notWritable', 'setupFailed',
  'helperUnavailable', 'logFailed', 'logFile', 'assistance', 'invalidEnv',
  'installationLocked', 'legacyRestart', 'downloadFailed', 'checkingUpdates',
  'downloadingVersion', 'verificationFailed', 'preparingVersion', 'activationFailed',
  'activatingVersion', 'cancelled', 'startupFailed',
]);
const bootstrap = 'param([switch]$InstallOnly)\n' + generated
  + messages(entries.filter(entry => bootstrapMessages.has(entry.id)))
  + shared + read('windows-bootstrap.ps1');
const installed = 'param([switch]$Installed,[string]$Installation,[string]$Invoking,[string]$Language)\n# ORE capability: bounded-release-comparison\n'
  + generated + messages(entries) + shared + read('windows-package-body.ps1');
// cmd.exe requires a CRLF batch envelope even when generation runs on POSIX.
const external = (batch + bootstrap).replaceAll('\r\n', '\n').replaceAll('\n', '\r\n');
for (const [name, content] of [['ORE-launcher.bat', external], ['scripts/release/windows-package-launcher.ps1', '\ufeff' + installed]]) {
  const path = resolve(root, name);
  if (process.argv.includes('--check')) {
    const actual = readFileSync(path, 'utf8');
    if ((name === 'ORE-launcher.bat' ? actual : actual.replaceAll('\r\n', '\n')) !== content) throw new Error(`Regenerate ${name}`);
  } else writeFileSync(path, content);
}
