import { openChatTool } from './chat-tools';
import { test, expect } from '@playwright/test';
import type { ChatSnapshot } from '../../src/shared/contracts';
import type { LibrarySnapshot } from '../../src/shared/library';
import { defaultContextPreset } from '../../src/shared/context';

test('keeps chat and memory budget panels mounted during debounced and delayed refreshes', async ({ page, request }) => {
  const session = await request.get('/api/session').then(response => response.json());
  const { endpoint } = await request.get('/__test/endpoint').then(response => response.json());
  await request.post('/__test/mode', { data: { mode: 'normal' } });
  await page.goto('/');
  await page.getByLabel('Owner password').fill('browser-synthetic-password');
  await page.getByRole('button', { name: session.setupRequired ? 'Create owner account' : 'Sign in', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Libraries', exact: true })).toBeVisible();
  const libraries = () => page.request.get('/api/library').then(response => response.json() as Promise<LibrarySnapshot>);
  const command = async (url: string, data: unknown, method = 'POST') => {
    const response = await page.request.fetch(url, { method, headers: { Origin: 'http://127.0.0.1:4173' }, data });
    expect(response.ok(), await response.text()).toBe(true); return response.json();
  };
  const { id: connectionId } = await command('/api/library', { revision: (await libraries()).revision, kind: 'connections', data: { name: 'Stable UI model', endpoint, model: 'synthetic-roleplay', contextWindow: 100_000, maxOutputTokens: 1_000, customParameters: {} } });
  const { id: contextId } = await command('/api/library', { revision: (await libraries()).revision, kind: 'contexts', data: { ...defaultContextPreset, name: 'Stable UI memory', connectionId, minTail: 2, batchSize: 2, retainedPerLevel: 1, promotionGroup: 2 } });
  const { id: chatId } = await command('/api/chats', { title: 'Stable budget proof', targetInputTokens: 20_000, connectionId, promptId: 'default', characterId: null, personaId: null, contextPresetId: contextId });
  await command(`/api/chats/${chatId}/history`, { revision: 0, turns: Array.from({ length: 8 }, () => ({ user: 'Mira offers Leon her brass key. '.repeat(12), assistant: 'Leon promises to avoid the cellar. '.repeat(12), complete: true })) }, 'PUT');
  await page.getByRole('button', { name: 'Libraries', exact: true }).click();
  await page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Stable budget proof', exact: true }) }).click();
  const context = page.locator('.context-dropdown');
  await context.locator('summary').click();
  await expect(context.locator('.allocation-legend')).toBeVisible();
  const meter = await context.getByRole('meter').elementHandle();
  const estimate = page.locator('.story-meta dl div').filter({ hasText: 'Estimated input' }).locator('dd');
  const originalEstimate = await estimate.textContent();
  let releasePreview!: () => void;
  const previewGate = new Promise<void>(resolve => { releasePreview = resolve; });
  let holdPreview = true;
  const previews: string[] = [], completed: string[] = [];
  await page.route(`**/api/chats/${chatId}/preview`, async route => {
    const hold = holdPreview, text = route.request().postDataJSON().text as string;
    previews.push(text);
    const response = await route.fetch();
    if (hold) await previewGate;
    await route.fulfill({ response }); completed.push(text);
  });
  const input = page.getByLabel('Your next turn');
  await input.fill('Mira');
  await page.waitForTimeout(600);
  expect(previews).toEqual([]);
  await input.pressSequentially(' waits', { delay: 60 });
  await page.waitForTimeout(600);
  expect(previews).toEqual([]);
  expect(await meter!.evaluate(node => node.isConnected)).toBe(true);
  await expect(estimate).toHaveText(originalEstimate!);
  await expect.poll(() => previews).toEqual(['Mira waits']);
  await expect(context.locator('.allocation-legend')).toBeVisible();
  await expect(page.getByText('Counting current input…', { exact: true })).toHaveCount(0);
  holdPreview = false;
  await input.fill('Mira waits by the cellar door.');
  await expect.poll(() => completed).toContain('Mira waits by the cellar door.');
  await expect(estimate).not.toHaveText(originalEstimate!);
  const latestEstimate = await estimate.textContent();
  releasePreview();
  await expect.poll(() => completed).toContain('Mira waits');
  await expect(estimate).toHaveText(latestEstimate!);
  expect(await meter!.evaluate(node => node.isConnected)).toBe(true);
  await expect(context).toHaveAttribute('open', '');

  await page.getByRole('button', { name: 'Story', exact: true }).click();
  await openChatTool(page, 'Inspect memory');
  const budget = page.locator('.memory-panel .budget');
  await expect(budget.locator('strong')).toContainText('/ 20,000');
  const budgetNode = await budget.elementHandle();
  const oldBudget = await budget.locator('strong').textContent();
  let releasePlan!: () => void;
  let planGate = new Promise<void>(resolve => { releasePlan = resolve; });
  let planRequests = 0;
  await page.route(`**/api/chats/${chatId}/context/plan`, async route => {
    const gate = planGate; planRequests++;
    const response = await route.fetch();
    await gate; await route.fulfill({ response });
  });
  await page.getByLabel('Input target', { exact: true }).fill('700');
  await page.getByRole('button', { name: 'Save memory settings', exact: true }).click();
  await expect.poll(() => planRequests).toBeGreaterThan(0);
  await expect(budget.locator('strong')).toHaveText(oldBudget!);
  expect(await budgetNode!.evaluate(node => node.isConnected)).toBe(true);
  await expect(page.getByText('Counting current input…', { exact: true })).toHaveCount(0);
  releasePlan();
  await expect(budget.locator('strong')).toContainText('/ 700');
  await expect(page.getByRole('button', { name: 'Prepare chat', exact: true })).toBeEnabled();
  const beforePrepare = await budget.locator('strong').textContent(), previousRequests = planRequests;
  planGate = new Promise<void>(resolve => { releasePlan = resolve; });
  await page.getByRole('button', { name: 'Prepare chat', exact: true }).click();
  await expect.poll(() => planRequests).toBeGreaterThan(previousRequests);
  await expect(budget.locator('strong')).toHaveText(beforePrepare!);
  expect(await budgetNode!.evaluate(node => node.isConnected)).toBe(true);
  await expect(page.getByText('Counting current input…', { exact: true })).toHaveCount(0);
  releasePlan();
  await expect(page.getByTestId('memory-status')).toContainText('Ready:');
  await expect(budget.locator('strong')).not.toHaveText(beforePrepare!);
  const snapshot = await page.request.get(`/api/chats/${chatId}`).then(response => response.json() as Promise<ChatSnapshot>);
  expect(snapshot.context.archivedTurnIds.length).toBeGreaterThan(0);
});

for (const width of [1280, 801, 800, 390, 320]) test(`automatically clears the server warning after initial and active-session outages at ${width}px`, async ({ page, request }) => {
  await page.setViewportSize({ width, height: 700 });
  const session = await request.get('/api/session').then(response => response.json());
  const warning = 'Cannot reach the server. Check that it is running.';
  await page.route('**/api/session', route => route.abort('failed'));
  await page.goto('/');
  await expect(page.getByRole('alert')).toHaveText(warning);
  await page.unroute('**/api/session');
  await expect(page.getByLabel('Owner password')).toBeVisible();
  await expect(page.getByRole('alert')).toHaveCount(0);
  await page.getByLabel('Owner password').fill('browser-synthetic-password');
  await page.getByRole('button', { name: session.setupRequired ? 'Create owner account' : 'Sign in', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Libraries', exact: true })).toBeVisible();
  await page.getByRole('navigation', { name: 'Workspace' }).getByRole('button', { name: 'Settings', exact: true }).click();
  await page.context().setOffline(true);
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
  await expect(page.locator('.error-banner')).toContainText(warning);
  const header = await page.locator('.topbar').boundingBox();
  const banner = await page.locator('.error-banner').boundingBox();
  const content = await page.getByRole('main').boundingBox();
  if (!header || !banner || !content) throw new Error('Missing workspace or server warning');
  expect(banner.y).toBeGreaterThanOrEqual(header.y + header.height);
  expect(banner.y + banner.height).toBeLessThanOrEqual(content.y);
  await expect(page.locator('.error-banner')).toBeInViewport();
  const retry = await page.getByRole('button', { name: 'Retry loading', exact: true }).boundingBox();
  const dismiss = await page.getByRole('button', { name: 'Dismiss', exact: true }).boundingBox();
  if (!retry || !dismiss) throw new Error('Missing server warning actions');
  expect(Math.abs(retry.y - dismiss.y)).toBeLessThan(1);
  expect(dismiss.x - (retry.x + retry.width)).toBeCloseTo(8, 0);
  expect(banner.x + banner.width - (dismiss.x + dismiss.width)).toBeCloseTo(width > 800 ? 30 : 16, 0);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: test.info().outputPath(`server-warning-${width}.png`) });
  await page.context().setOffline(false);
  await expect(page.locator('.error-banner')).toHaveCount(0, { timeout: 10_000 });
  await expect(page.locator('.connection-status')).toHaveText('Connected', { timeout: 10_000 });
});
