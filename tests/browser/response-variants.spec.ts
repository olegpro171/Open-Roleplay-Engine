import { expect, devices } from '@playwright/test';
import { test } from './appearance-test';
import type { ChatSnapshot } from '../../src/shared/contracts';
import type { LibrarySnapshot } from '../../src/shared/library';
import { defaultContextPreset } from '../../src/shared/context';

test('switches response versions with arrows and a textbox, restores summarized variants and survives reload on desktop and phone', async ({ page, browser, request, setAppearance }) => {
  test.setTimeout(60000);
  const session = await request.get('/api/session').then(response => response.json());
  await request.post('/__test/mode', { data: { mode: 'normal' } });
  await page.goto('/'); await page.getByLabel('Owner password').fill('browser-synthetic-password');
  await page.getByRole('button', { name: session.setupRequired ? 'Create owner account' : 'Sign in', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Libraries', exact: true })).toBeVisible();
  await setAppearance({ theme: 'dark' });
  const libraries = () => page.request.get('/api/library').then(response => response.json() as Promise<LibrarySnapshot>);
  const command = async (url: string, data: unknown, method = 'POST') => {
    const response = await page.request.fetch(url, { method, headers: { Origin: 'http://127.0.0.1:4173' }, data });
    expect(response.ok(), await response.text()).toBe(true); return response.json();
  };
  const { endpoint } = await request.get('/__test/endpoint').then(response => response.json());
  const connection = await command('/api/library', { revision: (await libraries()).revision, kind: 'connections', data: { name: 'Variant model', model: 'synthetic-roleplay', endpoint, contextWindow: 100000, maxOutputTokens: 1000, customParameters: {} } });
  const preset = await command('/api/library', { revision: (await libraries()).revision, kind: 'contexts', data: { ...defaultContextPreset, connectionId: connection.id, minTail: 1, batchSize: 1, retainedPerLevel: 0 } });
  const chat = await command('/api/chats', { title: 'Variant proof', targetInputTokens: 10000, connectionId: connection.id, promptId: 'default', characterId: null, personaId: null, contextPresetId: preset.id });
  const state = () => page.request.get(`/api/chats/${chat.id}`).then(response => response.json() as Promise<ChatSnapshot>);
  await command(`/api/chats/${chat.id}/history`, { revision: (await state()).revision, turns: [{ user: 'An invitation. ' + 'The rain falls. '.repeat(100), assistant: 'Original A.', complete: true }] }, 'PUT');
  await page.reload();
  await page.getByRole('button', { name: 'Libraries', exact: true }).click();
  await page.getByRole('button', { name: 'Chats', exact: true }).click();
  await page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Variant proof', exact: true }) }).click();
  await expect(page.getByText('Original A.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Regenerate response', exact: true }).hover();
  await expect(page.getByRole('button', { name: 'Regenerate response', exact: true })).toHaveCSS('background-color', 'rgb(37, 46, 56)');
  await page.getByRole('button', { name: 'Regenerate response', exact: true }).click();
  await expect.poll(async () => (await state()).turns[0].variants?.length).toBe(2);
  const generated = await state(), originalId = generated.turns[0].variants?.[0].id;
  const turn = page.getByRole('article', { name: 'Turn 1', exact: true });
  const version = turn.getByRole('textbox', { name: 'Response version', exact: true });
  const previous = turn.getByRole('button', { name: 'Previous response', exact: true });
  const next = turn.getByRole('button', { name: 'Next response', exact: true });
  await expect(version).toHaveValue('2');
  await expect(turn.getByLabel('2 response versions', { exact: true })).toHaveText('/ 2');
  // The newest response now offers a new regeneration through the right arrow.
  await expect(next).toBeEnabled();
  await expect(next).toHaveAttribute('title', 'Regenerate response');
  await expect(page.getByRole('button', { name: 'Inspect response request', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Use this response', exact: true })).toHaveCount(0);
  await previous.click();
  await expect.poll(async () => (await state()).turns[0].assistant.variantId).toBe(originalId);
  await expect(version).toHaveValue('1');
  await expect(previous).toBeDisabled();
  const firstRevision = (await state()).revision;
  await version.fill('2');
  expect((await state()).revision).toBe(firstRevision);
  await version.press('Enter');
  await expect.poll(async () => (await state()).turns[0].assistant.variantId).toBe(generated.turns[0].assistant.variantId);
  await expect(version).toHaveValue('2');
  await version.fill('1'); await version.press('Tab');
  await expect.poll(async () => (await state()).turns[0].assistant.variantId).toBe(originalId);
  await expect(version).toHaveValue('1');
  const unchangedRevision = (await state()).revision;
  for (const invalid of ['0', '999', 'abc', '']) {
    await version.fill(invalid); await version.press('Enter');
    await expect(version).toHaveValue('1');
    expect((await state()).revision).toBe(unchangedRevision);
  }
  await version.fill('2'); await version.press('Escape');
  await expect(version).toHaveValue('1');
  expect((await state()).revision).toBe(unchangedRevision);
  await next.click(); await expect(version).toHaveValue('2');
  const arrowRevision = (await state()).revision;
  await version.fill('1'); await previous.click();
  await expect(version).toHaveValue('1');
  expect((await state()).revision).toBe(arrowRevision + 1);
  // A delayed failed save must not replace the current text or counter.
  const selectUrl = `**/api/chats/${chat.id}/turns/${generated.turns[0].id}/variants/*/select`;
  let releaseSelection = () => {};
  const selectionGate = new Promise<void>(resolve => { releaseSelection = resolve; });
  await page.route(selectUrl, async route => {
    await selectionGate;
    await route.fulfill({ status: 409, contentType: 'application/json', body: JSON.stringify({ message: 'Synthetic selection conflict' }) });
  });
  const composer = page.getByLabel('Your next turn');
  await composer.fill('Draft stays while switching responses.');
  const sendButton = page.getByRole('button', { name: 'Send', exact: true });
  await expect(sendButton).toBeEnabled();
  const sendBounds = await sendButton.boundingBox(), composerBounds = await composer.boundingBox();
  expect(sendBounds).not.toBeNull();
  expect(composerBounds).not.toBeNull();
  await next.click();
  await expect(version).toBeDisabled();
  await expect(sendButton).toBeVisible();
  await expect(sendButton).toBeDisabled();
  await expect(sendButton).toHaveAttribute('title', 'Saving changes…');
  expect(await sendButton.boundingBox()).toEqual(sendBounds);
  expect(await composer.boundingBox()).toEqual(composerBounds);
  await expect(version).toHaveValue('1');
  await expect(turn.locator('.part.assistant .prose')).toHaveText('Original A.');
  releaseSelection();
  await expect(page.getByRole('alert')).toContainText('Synthetic selection conflict');
  await expect(version).toBeEnabled();
  await expect(sendButton).toBeEnabled();
  await expect(sendButton).toHaveAttribute('title', /^Send \(Ctrl(?: \/ ⌘)? \+ Enter\)$/);
  await expect(composer).toHaveValue('Draft stays while switching responses.');
  await expect(version).toHaveValue('1');
  expect((await state()).revision).toBe(arrowRevision + 1);
  await page.unroute(selectUrl);
  await turn.getByRole('group', { name: 'Turn controls', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/desktop-response-variants.png', fullPage: true });
  await page.reload(); await expect(turn.locator('.part.assistant .prose')).toHaveText('Original A.');
  await request.post('/__test/mode', { data: { mode: 'hold-first-token' } });
  const callsBeforeWait = await request.get('/__test/requests').then(response => response.json()).then(calls => calls.length);
  await page.getByLabel('Your next turn').fill('Unsent draft stays here');
  await page.getByRole('button', { name: 'Regenerate response', exact: true }).click();
  await expect(turn.locator('.part.assistant .prose')).toHaveText('Connecting…');
  await expect(page.getByLabel('Regeneration preview')).toHaveCount(0);
  await expect(turn.getByRole('button', { name: 'Cancel', exact: true })).toBeEnabled();
  await expect(turn.getByRole('button', { name: 'Regenerate response', exact: true })).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Cancel', exact: true })).toHaveCount(1);
  await expect(page.getByText('Regenerating…', { exact: true })).toHaveCount(0);
  await expect(page.getByText('The selected response is kept until regeneration succeeds.', { exact: true })).toHaveCount(0);
  expect((await state()).turns[0].assistant.text).toBe('Original A.');
  await expect.poll(() => request.get('/__test/requests').then(response => response.json()).then(calls => calls.length)).toBe(callsBeforeWait + 1);
  await request.post('/__test/finish', { data: {} });
  await expect(turn.locator('.part.assistant .prose')).toHaveText('The lantern');
  await expect(turn.getByLabel('Generating', { exact: true })).toBeVisible();
  await page.reload();
  await expect(turn.locator('.part.assistant .prose')).toHaveText('The lantern');
  for (const width of [1280, 390]) {
    await page.setViewportSize({ width, height: 844 });
    await turn.locator('.part.assistant').scrollIntoViewIfNeeded();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `test-results/${width === 390 ? 'phone' : 'desktop'}-regeneration-inline.png`, fullPage: true });
  }
  await expect(page.getByLabel('Your next turn')).toBeEnabled();
  await turn.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(turn.locator('.part.assistant .prose')).toHaveText('Original A.');
  await expect(page.getByLabel('Your next turn')).toBeEnabled();
  await expect(turn.getByRole('button', { name: 'Regenerate response', exact: true })).toBeEnabled();
  await expect(turn.getByRole('button', { name: 'Cancel', exact: true })).toHaveCount(0);
  await expect(page.getByRole('status').filter({ hasText: 'Regeneration cancelled' })).toHaveCount(0);
  await expect(page.getByLabel('Your next turn')).toHaveValue('Unsent draft stays here');
  expect((await state()).turns[0].variants).toHaveLength(2);
  // Touch browsers can retain :hover when Regenerate changes into Cancel.
  const phoneContext = await browser.newContext({ ...devices['iPhone 13'] });
  try {
    const phone = await phoneContext.newPage();
    await phone.goto('/');
    await phone.getByLabel('Owner password').fill('browser-synthetic-password');
    await phone.getByRole('button', { name: 'Sign in', exact: true }).click();
    await phone.getByRole('button', { name: 'Libraries', exact: true }).click();
    await phone.getByRole('button', { name: 'Chats', exact: true }).click();
    await phone.getByRole('article').filter({ has: phone.getByRole('heading', { name: 'Variant proof', exact: true }) }).tap();
    await phone.getByRole('button', { name: 'Regenerate response', exact: true }).tap();
    const stop = phone.getByRole('button', { name: 'Cancel', exact: true });
    await expect(stop).toBeEnabled();
    await expect(phone.getByText('Connecting…', { exact: true })).toBeVisible();
    // Chromium clears touch hover here; retain it explicitly to model sticky-hover phone browsers.
    await stop.hover();
    await expect(stop).toHaveCSS('background-color', 'rgba(0, 0, 0, 0)');
    await expect(stop).toHaveCSS('filter', 'none');
    await expect(stop).toHaveCSS('-webkit-tap-highlight-color', 'rgba(0, 0, 0, 0)');
    await expect(stop).toHaveCSS('color', 'rgb(228, 170, 127)');
    await phone.screenshot({ path: 'test-results/phone-regeneration-touch.png', fullPage: true });
    await stop.tap();
    await expect(phone.getByRole('button', { name: 'Regenerate response', exact: true })).toBeEnabled();
    await expect(phone.getByRole('article', { name: 'Turn 1', exact: true }).locator('.part.assistant .prose')).toHaveText('Original A.');
  } finally {
    await phoneContext.close();
  }
  await expect(turn.getByRole('button', { name: 'Regenerate response', exact: true })).toBeEnabled();
  // A completed replacement stays in the same container and becomes a variant.
  const callsBeforeSuccess = await request.get('/__test/requests').then(response => response.json()).then(calls => calls.length);
  await page.getByRole('button', { name: 'Regenerate response', exact: true }).click();
  await expect(turn.locator('.part.assistant .prose')).toHaveText('Connecting…');
  await expect.poll(() => request.get('/__test/requests').then(response => response.json()).then(calls => calls.length)).toBe(callsBeforeSuccess + 1);
  await request.post('/__test/finish', { data: {} });
  await expect(turn.locator('.part.assistant .prose')).toHaveText('The lantern');
  await request.post('/__test/finish', { data: {} });
  await expect(turn.locator('.part.assistant .prose')).toHaveText('The lantern flickers. 🕯');
  await expect(version).toHaveValue('3');
  await expect.poll(async () => (await state()).turns[0].variants?.length).toBe(3);
  await version.fill('1'); await version.press('Enter');
  await expect(turn.locator('.part.assistant .prose')).toHaveText('Original A.');
  await expect(version).toHaveValue('1');
  // A failed attempt must restore the selected response just like cancellation.
  await request.post('/__test/mode', { data: { mode: 'broken' } });
  await page.getByRole('button', { name: 'Regenerate response', exact: true }).click();
  await expect.poll(async () => (await state()).generations[0]?.status).toBe('failed');
  await expect(turn.locator('.part.assistant .prose')).toHaveText('Original A.');
  expect((await state()).turns[0].variants).toHaveLength(3);
  const failure = (await state()).generations[0].error;
  if (!failure) throw new Error('Missing fixture failure');
  await expect(page.getByRole('status').filter({ hasText: failure })).toBeVisible();
  await request.post('/__test/mode', { data: { mode: 'normal' } });
  await page.getByLabel('Your next turn').fill('Later input');
  await page.getByRole('button', { name: 'Send', exact: true }).click();
  await expect(page.getByRole('article')).toHaveCount(2);
  await expect(page.getByLabel('Your next turn')).toBeEnabled();
  await command(`/api/chats/${chat.id}/selections`, { revision: (await state()).revision, settings: { title: 'Variant proof', targetInputTokens: 200, connectionId: connection.id, promptId: 'default', characterId: null, personaId: null, contextPresetId: preset.id } }, 'PUT');
  await command(`/api/chats/${chat.id}/context/prepare`, { revision: (await state()).revision, requestId: crypto.randomUUID(), mode: 'prepare' });
  await expect.poll(async () => (await state()).context.jobs[0]?.status).toBe('succeeded');
  await page.reload();
  await expect(turn).toContainText('ARCHIVED');
  await expect(turn.getByRole('button', { name: 'Regenerate response', exact: true })).toHaveCount(0);
  await page.setViewportSize({ width: 390, height: 844 });
  await next.click();
  await expect(version).toHaveValue('2');
  await expect(page.getByText('Memory needs review.', { exact: true })).toBeVisible();
  await turn.getByRole('group', { name: 'Turn controls', exact: true }).scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'test-results/phone-response-variants.png', fullPage: true });
  await previous.click();
  await expect(version).toHaveValue('1');
  await expect(page.getByText('Memory needs review.', { exact: true })).toHaveCount(0);
  expect((await state()).turns[0].assistant.variantId).toBe(originalId);
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
});
