import { test, expect } from '@playwright/test';
import type { ChatSnapshot, RequestPreview } from '../../src/shared/contracts';
import type { LibrarySnapshot } from '../../src/shared/library';

test('edits explicit markers, uses recent history, and enables preparation again without losing saved memory', async ({ page, request }) => {
  const session = await request.get('/api/session').then(response => response.json());
  const { endpoint } = await request.get('/__test/endpoint').then(response => response.json());
  await request.post('/__test/mode', { data: { mode: 'normal' } });
  await page.goto('/');
  await page.getByLabel('Owner password').fill('browser-synthetic-password');
  await page.getByRole('button', { name: session.setupRequired ? 'Create owner account' : 'Sign in', exact: true }).click();
  const library = () => page.request.get('/api/library').then(response => response.json() as Promise<LibrarySnapshot>);
  const command = async (url: string, data: unknown, method = 'POST') => {
    const response = await page.request.fetch(url, { method, headers: { Origin: 'http://127.0.0.1:4173' }, data });
    expect(response.ok(), await response.text()).toBe(true); return response.json();
  };
  await page.getByRole('button', { name: 'Libraries', exact: true }).click();
  await page.getByRole('button', { name: 'Prompts', exact: true }).click();
  await page.getByRole('button', { name: 'New prompt', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('Explicit prompt proof');
  await expect(page.locator('.prompt-block')).toHaveCount(5);
  await page.getByRole('button', { name: 'Expand block 4', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'Marker source for block 4', exact: true })).toContainText('Summary');
  await expect(page.locator('body')).not.toContainText('future compaction');
  await page.getByRole('checkbox', { name: 'Enable block 4', exact: true }).uncheck();
  await expect(page.getByRole('status').filter({ hasText: 'Summary marker is absent or disabled. Summaries will not be sent.' })).toBeVisible();
  await page.getByRole('button', { name: 'Save prompt', exact: true }).click();
  const prompt = (await library()).prompts.find(item => item.name === 'Explicit prompt proof')!;
  const model = await command('/api/library', { revision: (await library()).revision, kind: 'connections', data: { name: 'Prompt proof model', endpoint, model: 'synthetic-roleplay', contextWindow: 100_000, maxOutputTokens: 1_000, customParameters: {} } });
  const summary = await command('/api/library', { revision: (await library()).revision, kind: 'connections', data: { name: 'Prompt proof summaries', endpoint, model: 'synthetic-summary', contextWindow: 100_000, maxOutputTokens: 1_000, customParameters: {} } });
  const preset = (await library()).contexts[0];
  await command(`/api/library/${preset.id}`, { revision: (await library()).revision, kind: 'contexts', data: { name: preset.name, connectionId: summary.id, minTail: 1, batchSize: 2, summaryTokens: 100, promotionGroup: 2, retainedPerLevel: 0, extractionPrompt: preset.extractionPrompt, promotionPrompt: preset.promotionPrompt } }, 'PUT');
  const chat = await command('/api/chats', { title: 'Explicit prompt chat', targetInputTokens: 350, connectionId: model.id, promptId: prompt.id, characterId: null, personaId: null, contextPresetId: preset.id });
  const state = () => page.request.get(`/api/chats/${chat.id}`).then(response => response.json() as Promise<ChatSnapshot>);
  await command(`/api/chats/${chat.id}/history`, { revision: (await state()).revision, turns: Array.from({ length: 14 }, (_, i) => ({ user: `USER ${i}. ` + 'A brass key. '.repeat(20), assistant: `ASSISTANT ${i}. ` + 'The cellar is locked. '.repeat(10), complete: true })) }, 'PUT');
  await page.reload();
  await page.getByRole('button', { name: 'Libraries', exact: true }).click();
  await page.getByRole('button', { name: 'Chats', exact: true }).click();
  await page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Explicit prompt chat', exact: true }) }).getByRole('button', { name: 'Open chat', exact: true }).click();
  await page.getByRole('button', { name: 'Memory', exact: true }).click();
  await expect(page.getByTestId('memory-status')).toContainText('Summaries are disabled');
  await expect(page.getByRole('button', { name: 'Prepare chat', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Save next summary', exact: true })).toBeDisabled();
  await expect(page.getByRole('button', { name: 'Repair summaries', exact: true })).toBeDisabled();
  const requests = () => page.request.get('/__test/requests').then(response => response.json() as Promise<{ body: object }[]>);
  const calls = (await requests()).length;
  await page.getByRole('button', { name: 'Story', exact: true }).click();
  await page.locator('.context-dropdown > summary').click();
  await page.getByRole('button', { name: 'Prompt peek', exact: true }).click();
  const peek = page.getByRole('dialog', { name: 'Prompt peek' });
  await expect(peek).toContainText('Turn 14');
  await expect(peek).not.toContainText('Turn 1 ·');
  await expect(peek).not.toContainText('[Memory L');
  await page.getByRole('button', { name: 'Close peek', exact: true }).click();
  await page.getByRole('textbox', { name: 'Your next turn', exact: true }).fill('I return the key.');
  await expect.poll(async () => {
    const response = await page.request.post(`/api/chats/${chat.id}/preview`, { headers: { Origin: 'http://127.0.0.1:4173' }, data: { revision: (await state()).revision, inspection: true, text: 'I return the key.' } });
    return response.status();
  }).toBe(200);
  const preview = await page.request.post(`/api/chats/${chat.id}/preview`, { headers: { Origin: 'http://127.0.0.1:4173' }, data: { revision: (await state()).revision, inspection: true, text: 'I return the key.' } }).then(response => response.json() as Promise<RequestPreview>);
  await page.getByRole('button', { name: /^Send/ }).click();
  await expect.poll(async () => (await state()).generations[0]?.status).toBe('succeeded');
  expect((await requests()).length).toBe(calls + 1);
  expect((await requests()).at(-1)!.body).toEqual(preview.body);
  expect((await state()).context.jobs).toEqual([]);
  const enabledBlocks = prompt.blocks.map(block => ({ ...block, enabled: true }));
  await command(`/api/library/${prompt.id}`, { revision: (await library()).revision, kind: 'prompts', data: { name: prompt.name, blocks: enabledBlocks } }, 'PUT');
  await page.getByRole('button', { name: 'Memory', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Prepare chat', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Prepare chat', exact: true }).click();
  await expect(page.getByTestId('memory-status')).toContainText('Ready:', { timeout: 15_000 });
  const memory = structuredClone((await state()).context);
  expect(memory.summaries.length).toBeGreaterThan(0);
  await command(`/api/library/${prompt.id}`, { revision: (await library()).revision, kind: 'prompts', data: { name: prompt.name, blocks: prompt.blocks } }, 'PUT');
  await expect(page.getByTestId('memory-status')).toContainText('Summaries are disabled');
  expect((await state()).context).toEqual(memory);
  await page.setViewportSize({ width: 390, height: 844 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/prompt-control-phone.png', fullPage: true });
});

test('saves a prompt with every block removed and shows generic advisory warnings', async ({ page, request }) => {
  const session = await request.get('/api/session').then(response => response.json());
  await page.goto('/'); await page.getByLabel('Owner password').fill('browser-synthetic-password');
  await page.getByRole('button', { name: session.setupRequired ? 'Create owner account' : 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'Libraries', exact: true }).click();
  await page.getByRole('button', { name: 'Prompts', exact: true }).click();
  await page.getByRole('button', { name: 'New prompt', exact: true }).click();
  await page.getByLabel('Name', { exact: true }).fill('Empty prompt proof');
  for (let i = 0; i < 5; i++) await page.getByRole('button', { name: 'Remove block 1', exact: true }).click();
  await expect(page.locator('.prompt-block')).toHaveCount(0);
  await expect(page.getByRole('status').filter({ hasText: 'marker' })).toHaveCount(4);
  await page.getByRole('button', { name: 'Save prompt', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Empty prompt proof', exact: true })).toBeVisible();
  const library = await page.request.get('/api/library').then(response => response.json() as Promise<LibrarySnapshot>);
  expect(library.prompts.find(prompt => prompt.name === 'Empty prompt proof')!.blocks).toEqual([]);
});
