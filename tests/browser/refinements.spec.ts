import { test, expect, devices } from '@playwright/test';
import type { ChatSnapshot } from '../../src/shared/contracts';
import type { LibrarySnapshot } from '../../src/shared/library';
import { defaultContextPreset } from '../../src/shared/context';
import { assembleRequest } from '../../src/core/prompt';

test('live input inspection, budget recovery, provider usage and clearing every memory layer', async ({ page, browser, request }) => {
  const password = 'browser-synthetic-password';
  const session = await request.get('/api/session').then(response => response.json());
  const { endpoint } = await request.get('/__test/endpoint').then(response => response.json());
  await page.goto('/');
  await page.getByLabel('Owner password').fill(password);
  await page.getByRole('button', { name: session.setupRequired ? 'Create owner account' : 'Sign in', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Libraries', exact: true })).toBeVisible();
  const libraries = () => page.request.get('/api/library').then(response => response.json() as Promise<LibrarySnapshot>);
  const command = async (url: string, data: unknown, method = 'POST') => {
    const response = await page.request.fetch(url, { method, headers: { Origin: 'http://127.0.0.1:4173' }, data });
    expect(response.ok(), await response.text()).toBe(true); return response.json();
  };
  const { id: connectionId } = await command('/api/library', { revision: (await libraries()).revision, kind: 'connections', data: { name: 'Refinement model', endpoint, model: 'synthetic-roleplay', contextWindow: 100_000, maxOutputTokens: 1_000, customParameters: {} } });
  const preset = { ...defaultContextPreset, name: 'Refinement memory', connectionId, minTail: 2, batchSize: 2, promotionGroup: 2, retainedPerLevel: 1 };
  const { id: contextId } = await command('/api/library', { revision: (await libraries()).revision, kind: 'contexts', data: preset });
  const { id: chatId } = await command('/api/chats', { title: 'Refinement proof', targetInputTokens: 35_000, connectionId, promptId: 'default', characterId: null, personaId: null, contextPresetId: contextId });
  const state = () => page.request.get(`/api/chats/${chatId}`).then(response => response.json() as Promise<ChatSnapshot>);
  await command(`/api/chats/${chatId}/history`, { revision: (await state()).revision, turns: Array.from({ length: 8 }, (_, i) => ({ user: `Turn ${i + 1}. ${'Mira offers Leon her brass key. '.repeat(7)}`, assistant: 'Leon promises to stay out of the cellar. '.repeat(7), complete: true })) }, 'PUT');
  await page.getByRole('button', { name: 'Libraries', exact: true }).click();
  await page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Refinement proof', exact: true }) }).getByRole('button', { name: 'Open chat', exact: true }).click();
  const meta = page.locator('.story-meta');
  await expect(meta.locator('dl div').filter({ hasText: 'Total turns' })).toHaveText('Total turns8');
  await expect(meta.locator('dl div').filter({ hasText: 'Active turns' })).toHaveText('Active turns8');
  await expect(page.getByText('Your transcript is saved on the Mac.', { exact: true })).toHaveCount(0);
  await expect(page.locator('.composer label')).toHaveCount(0);
  const estimate = meta.locator('dl div').filter({ hasText: 'Estimated input' }).locator('dd');
  const before = await estimate.textContent();
  await page.getByLabel('Your next turn').fill('Mira keeps the key for herself.');
  await expect(estimate).not.toHaveText(before!);
  await meta.locator('.context-dropdown > summary').click();
  await meta.getByRole('button', { name: 'Prompt peek', exact: true }).click();
  const peek = page.getByRole('dialog', { name: 'Prompt peek' });
  await expect(peek).toBeVisible();
  await expect(peek.locator('.allocation-legend')).toContainText('Unsent input');
  await peek.locator('.prompt-message').filter({ hasText: 'Unsent input' }).locator('summary').click();
  await expect(peek).toContainText('Mira keeps the key for herself.');
  expect(await peek.locator('.prompt-message').count()).toBe(18);
  await peek.evaluate(node => { node.scrollTop = 0; });
  await page.screenshot({ path: 'test-results/desktop-prompt-peek.png', fullPage: true });
  await page.keyboard.press('Escape'); await expect(peek).toHaveCount(0);
  await expect(meta.getByRole('button', { name: 'Prompt peek', exact: true })).toBeFocused();
  await page.getByRole('button', { name: 'Send turn' }).click();
  await expect(page.getByLabel('Your next turn')).toBeEnabled();
  await expect(page.locator('.turn-usage').last()).toHaveText('321 in · 17 out');
  const originalRequest = (await state()).generations[0].request;
  expect(originalRequest?.budget.targetInputTokens).toBe(35_000);

  await page.getByRole('button', { name: 'Memory', exact: true }).click();
  await page.getByLabel('Input target', { exact: true }).fill('2200');
  await page.getByRole('button', { name: 'Save memory settings', exact: true }).click();
  await expect(page.getByRole('meter', { name: 'Input budget' })).toHaveClass(/overflow/);
  await expect(page.locator('.budget')).toHaveCSS('background-color', 'rgb(27, 33, 42)');
  await page.getByRole('button', { name: 'Save next summary', exact: true }).click();
  await expect.poll(async () => (await state()).context.jobs[0]?.status).toBe('succeeded');
  const saved = await state();
  const tail = saved.turns.filter(turn => !saved.context.archivedTurnIds.includes(turn.id));
  const required = assembleRequest(saved.connection!, saved.settings, tail, saved.sources, undefined, { validateLimits: false }).budget.inputTokens;
  await command(`/api/library/${contextId}`, { revision: (await libraries()).revision, kind: 'contexts', data: { ...preset, minTail: tail.length } }, 'PUT');
  await command(`/api/chats/${chatId}/selections`, { revision: (await state()).revision, settings: { title: saved.settings.title, targetInputTokens: required + 1, connectionId, promptId: 'default', characterId: null, personaId: null, contextPresetId: contextId } }, 'PUT');
  await command(`/api/chats/${chatId}/context/prepare`, { revision: (await state()).revision, requestId: crypto.randomUUID(), mode: 'prepare' });
  await expect(page.getByTestId('memory-status')).toContainText('retained-summary floor');
  await expect(page.getByRole('button', { name: 'Prepare chat', exact: true })).toBeDisabled();

  await page.getByRole('button', { name: 'Setup', exact: true }).click();
  await page.getByLabel('Target input tokens').fill('45000');
  await page.getByRole('button', { name: 'Save setup', exact: true }).click();
  await expect(meta.locator('dl div').filter({ hasText: 'Active turns' })).toHaveText('Active turns7');
  await page.getByRole('button', { name: 'Request inspector', exact: true }).click();
  await expect(page.locator('.budget strong')).toContainText('/ 45,000');
  await page.getByRole('combobox', { name: 'Inspect request', exact: true }).click();
  await page.getByRole('option').filter({ hasText: 'succeeded' }).first().click();
  await expect(page.locator('.budget strong')).toContainText('/ 35,000');
  expect(JSON.parse((await page.getByTestId('request-body').textContent())!)).toEqual(originalRequest!.body);
  await page.getByRole('button', { name: 'Memory', exact: true }).click();
  await expect(page.getByTestId('memory-status')).toContainText('Ready:');
  await expect(page.locator('.memory-failure')).toHaveCount(0);
  await expect(page.getByRole('meter', { name: 'Input budget' })).toHaveClass(/fits/);
  await command(`/api/library/${contextId}`, { revision: (await libraries()).revision, kind: 'contexts', data: preset }, 'PUT');
  await page.getByLabel('Input target', { exact: true }).fill('2200');
  await page.getByRole('button', { name: 'Save memory settings', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Prepare chat', exact: true })).toBeEnabled();
  await expect(page.getByRole('button', { name: 'Save next summary', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: 'Prepare chat', exact: true }).click();
  await expect(page.getByTestId('memory-status')).toContainText('Ready:');
  expect((await state()).context.summaries.length).toBeGreaterThan(0);

  const phoneContext = await browser.newContext({ ...devices['iPhone 13'] });
  const phone = await phoneContext.newPage();
  await phone.goto('http://127.0.0.1:4173/'); await phone.getByLabel('Owner password').fill(password);
  await phone.getByRole('button', { name: 'Sign in', exact: true }).click();
  await phone.getByRole('button', { name: 'Libraries', exact: true }).click();
  await phone.getByRole('article').filter({ has: phone.getByRole('heading', { name: 'Refinement proof', exact: true }) }).getByRole('button', { name: 'Open chat', exact: true }).click();
  await phone.getByRole('button', { name: 'Request inspector', exact: true }).click();
  await phone.getByRole('button', { name: 'Prompt peek', exact: true }).click();
  await expect(phone.getByRole('dialog', { name: 'Prompt peek' })).toBeVisible();
  expect(await phone.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await phone.screenshot({ path: 'test-results/phone-prompt-peek.png', fullPage: true });
  await phone.getByRole('button', { name: 'Close peek' }).click();
  await phoneContext.close();

  await page.locator('.restore-memory > summary').click();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Clear memory', exact: true }).click();
  await expect(page.locator('.summary-span:not(.preparing)')).toHaveCount(0);
  const cleared = await state();
  expect(cleared.context.jobs).toEqual([]); expect(cleared.context.summaries).toEqual([]);
  expect(cleared.context.archivedTurnIds).toEqual([]); expect(cleared.turns).toHaveLength(9);
  expect(cleared.generations[0].request).toEqual(originalRequest);
});
