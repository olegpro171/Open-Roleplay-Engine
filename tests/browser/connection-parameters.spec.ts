import { expect } from '@playwright/test';
import { test } from './isolated-app';
import { appearanceStatusSchema, themeSchema } from '../../src/shared/appearance';
import type { LibrarySnapshot } from '../../src/shared/library';

test('edits saved built-ins and tests and saves provider fields alongside them', async ({ page, browserApp }, testInfo) => {
  await page.goto('/');
  await page.getByLabel('Owner password').fill('browser-synthetic-password');
  await page.getByRole('button', { name: 'Create owner account', exact: true }).click();
  await expect(page.getByRole('navigation', { name: 'Workspace' })).toBeVisible();
  const headers = { Origin: browserApp.url };
  const library = async (): Promise<LibrarySnapshot> => page.request.get('/api/library').then(response => response.json());
  const { endpoint } = await page.request.get('/__test/endpoint').then(response => response.json());
  const name = 'Model parameters';
  const legacyParameters = { temperature: 0.7, top_p: 0.9, presence_penalty: -0.5, frequency_penalty: 0, seed: 7, stop: ['A\nB', 'C'], reasoning_effort: 'none' };
  const created = await page.request.post('/api/library', { headers, data: { kind: 'connections', revision: (await library()).revision, data: {
    name, endpoint, model: 'synthetic', contextWindow: 100_000, maxOutputTokens: 1000, customParameters: legacyParameters,
  }, apiKey: 'synthetic-parameter-secret' } });
  expect(created.ok(), await created.text()).toBe(true);

  await page.getByRole('button', { name: 'Libraries', exact: true }).click();
  await page.getByRole('button', { name: 'Connections', exact: true }).click();
  const savedConnection = page.getByRole('button', { name, exact: true });
  await savedConnection.click();
  const custom = page.getByLabel('Custom request parameters');
  const editorText = () => custom.innerText();
  const format = page.getByRole('button', { name: 'Format JSON', exact: true });
  const problem = page.getByRole('button', { name: /^Line \d+, column / });
  const advanced = page.locator('details').filter({ has: page.getByText('Advanced parameters', { exact: true }) });
  const advancedToggle = advanced.locator('summary');
  const temperature = page.getByLabel('Temperature', { exact: true });
  const topP = page.getByLabel('Top P', { exact: true });
  const reasoning = page.getByRole('combobox', { name: 'Reasoning effort', exact: true });
  const save = page.getByRole('group', { name: 'Editor actions' }).getByRole('button', { name: 'Save', exact: true });
  const sendTest = page.getByRole('button', { name: 'Send test message', exact: true });
  const requests = async () => page.request.get('/__test/requests').then(response => response.json());
  const settings = page.getByRole('tab', { name: 'Connection settings', exact: true });
  const parameters = page.getByRole('tab', { name: 'Request parameters', exact: true });
  const endpointField = page.getByLabel('API base URL');
  await expect(settings).toHaveAttribute('aria-selected', 'true');
  await endpointField.fill('unfinished');
  await settings.press('ArrowRight');
  await expect(parameters).toBeFocused();
  await save.click();
  await expect(endpointField).toBeFocused();
  await expect(endpointField).toHaveValue('unfinished');
  await endpointField.fill(`${endpoint}?format=detail`);
  await parameters.click();
  await sendTest.click();
  await expect(endpointField).toBeFocused();
  await expect(endpointField).toHaveAccessibleDescription(/Use an HTTP\(S\) API base URL/);
  await endpointField.fill(endpoint);
  await expect(endpointField).toHaveAccessibleDescription('');
  const connectionName = page.getByLabel('Name', { exact: true });
  await connectionName.fill('   ');
  await save.click();
  await expect(connectionName).toBeFocused();
  await expect(connectionName).toHaveAttribute('aria-invalid', 'true');
  await connectionName.fill(name);
  const reserve = page.getByLabel('Reserved output tokens', { exact: true });
  await reserve.fill('unfinished');
  await parameters.click();
  await sendTest.click();
  await expect(reserve).toBeFocused();
  expect(await requests()).toHaveLength(0);
  await reserve.fill('1000');
  await parameters.click();
  await expect(temperature).toHaveValue('0.7');
  await expect(topP).toHaveValue('0.9');
  await expect(temperature).toHaveAccessibleDescription(/Range 0–2\./);
  await expect(topP).toHaveAccessibleDescription(/Range 0–1\./);
  await expect(custom).toBeHidden();
  await expect(reasoning).toBeHidden();
  await sendTest.click();
  await expect(page.locator('.connection-success')).toBeVisible();
  expect((await requests())[0].body).toMatchObject(legacyParameters);

  await advancedToggle.focus();
  await advancedToggle.press('Enter');
  await expect(page.getByLabel('Presence penalty', { exact: true })).toHaveValue('-0.5');
  await expect(page.getByLabel('Frequency penalty', { exact: true })).toHaveValue('0');
  const seed = page.getByLabel('Seed', { exact: true });
  await expect(seed).toHaveValue('7');
  const firstStop = page.getByRole('textbox', { name: 'Stop sequence 1', exact: true });
  await expect(firstStop).toHaveValue('A\nB');
  expect(await firstStop.evaluate(field => field.clientHeight >= field.scrollHeight)).toBe(true);
  await expect(reasoning).toHaveText('none');
  await expect(advanced.getByLabel('Custom request parameters')).toBeVisible();
  await expect.poll(editorText).toBe('{}');

  await custom.fill('');
  await expect(page.getByRole('status').filter({ hasText: 'No custom parameters' })).toBeVisible();
  await expect(format).toBeDisabled();
  await custom.fill('{\n}');
  await custom.press('End');
  await custom.press('ArrowLeft');
  await custom.press('Tab');
  await expect.poll(editorText).toBe('{\n    }');
  await expect(custom).toBeFocused();
  await page.keyboard.insertText('"top_k": 4');
  await custom.press('Shift+ArrowLeft');
  await custom.press('Tab');
  await expect.poll(editorText).toBe('{\n    "top_k":     }');
  await custom.press('ControlOrMeta+z');
  await expect.poll(editorText).toBe('{\n    "top_k": 4}');
  await custom.press('Escape');
  await page.keyboard.press('Tab');
  await expect(custom).not.toBeFocused();
  await page.keyboard.press('Shift+Tab');
  await expect(custom).toBeFocused();
  await custom.press('Shift+Tab');
  await expect(custom).not.toBeFocused();

  await custom.fill('{\n    "top_k" 50\n}');
  await expect(problem).toContainText('Line 2, column 13');
  await expect(format).toBeDisabled();
  await problem.click();
  await expect(custom).toBeFocused();
  await page.keyboard.insertText(':');
  await expect.poll(editorText).toBe('{\n    "top_k" :50\n}');
  await expect(custom).toHaveAttribute('aria-invalid', 'false');
  await expect(problem).toHaveCount(0);

  // A wrapped first line and a scrolled source must still use logical line numbers.
  const wrapped = 'wrapped text '.repeat(80);
  const distant = ['{', `    "note": "${wrapped}",`, ...Array.from({ length: 40 }, (_, i) => `    "key${i}": true,`), '    "last":', '}'];
  await custom.fill(distant.join('\n'));
  await custom.press('ControlOrMeta+Home');
  await expect(problem).toContainText('Line 44, column 1');
  await problem.focus();
  await problem.press('Enter');
  await expect(custom).toBeFocused();
  await expect(page.locator('.connection-json-input .cm-lineNumbers').getByText('44', { exact: true })).toBeInViewport();
  await page.keyboard.insertText('null');
  await expect(custom).toHaveAttribute('aria-invalid', 'false');

  await custom.fill('[]');
  await expect(format).toBeDisabled();
  const compact = '{"nested":{"stream":true},"stream":false}';
  await custom.fill(compact);
  await expect(problem).toContainText('Line 1, column 27');
  await expect(format).toBeEnabled();
  await format.click();
  await expect(problem).toContainText('Line 5, column 5');
  await custom.press('ControlOrMeta+z');
  await expect.poll(editorText).toBe(compact);
  await expect(problem).toContainText('Line 1, column 27');
  await format.click();
  await settings.click();
  await sendTest.click();
  await expect(parameters).toHaveAttribute('aria-selected', 'true');
  await expect(custom).toBeFocused();
  expect(await requests()).toHaveLength(1);
  await problem.click();
  await custom.press('ArrowRight');
  await page.keyboard.insertText('extra_');
  await expect.poll(editorText).toBe('{\n    "nested": {\n        "stream": true\n    },\n    "extra_stream": false\n}');
  await expect(problem).toHaveCount(0);

  await custom.fill('{"temperature": 0.8}');
  await format.click();
  await advancedToggle.click();
  await settings.click();
  await save.click();
  await expect(parameters).toHaveAttribute('aria-selected', 'true');
  await expect(problem.filter({ hasText: 'Set temperature using its dedicated control' })).toBeVisible();
  await expect(custom).toBeFocused();
  await expect.poll(editorText).toBe('{\n    "temperature": 0.8\n}');
  await topP.fill('2');
  await custom.fill('{"top_k": 50}');
  await sendTest.click();
  await expect(topP).toBeFocused();
  await expect(topP).toHaveAccessibleDescription(/Range 0–1\..*Enter a number from 0 to 1 for top_p\./);
  expect(await requests()).toHaveLength(1);
  expect((await library()).connections.find(item => item.name === name)?.customParameters).toEqual(legacyParameters);

  await topP.fill('');
  await expect(topP).toHaveAccessibleDescription(/Range 0–1\./);
  await expect(page.getByText('Enter a number from 0 to 1 for top_p.', { exact: true })).toHaveCount(0);
  await seed.fill('1.5');
  await advancedToggle.click();
  await settings.click();
  await save.click();
  await expect(seed).toBeFocused();
  await expect(seed).toHaveAccessibleDescription(/Enter an integer .* for seed\./);
  await expect(seed).toHaveValue('1.5');
  await seed.fill('7');
  await expect(seed).toHaveAccessibleDescription('');
  await temperature.fill('0,35');
  await reasoning.click();
  await page.getByRole('option', { name: 'Provider default', exact: true }).click();
  const removeSecondStop = page.getByRole('button', { name: 'Remove stop sequence 2', exact: true });
  await expect(removeSecondStop).toHaveText('Remove');
  await removeSecondStop.click();
  const extras = { top_k: 50, chat_template_kwargs: { enable_thinking: false }, extras: [0, null, 'literal'] };
  await custom.fill(JSON.stringify(extras));
  await format.click();
  await expect.poll(editorText).toBe(JSON.stringify(extras, null, 4));
  await custom.press('ControlOrMeta+z');
  await expect.poll(editorText).toBe(JSON.stringify(extras));
  await format.click();
  await sendTest.click();
  await expect(page.locator('.connection-success')).toBeVisible();
  await page.getByText('Test request and response', { exact: true }).click();
  const sent = (await requests())[1];
  const expectedParameters = { ...extras, temperature: 0.35, presence_penalty: -0.5, frequency_penalty: 0, seed: 7, stop: ['A\nB'] };
  expect(sent.body).toEqual({ ...expectedParameters, model: 'synthetic', messages: [{ role: 'user', content: 'Hi' }], max_tokens: 1000, stream: true, stream_options: { include_usage: true } });
  await expect(page.locator('.connection-tools pre')).toContainText('"top_k": 50');
  await expect(page.locator('.connection-tools pre')).not.toContainText('synthetic-parameter-secret');
  await save.click();
  await expect(custom).toBeHidden();
  expect((await library()).connections.find(item => item.name === name)?.customParameters).toEqual(expectedParameters);
  await savedConnection.click();
  await parameters.click();
  await expect(temperature).toHaveValue('0.35');
  await expect(topP).toHaveValue('');
  await expect(custom).toBeHidden();
  await advancedToggle.click();
  await expect(reasoning).toHaveText('Provider default');
  await expect.poll(editorText).toBe(JSON.stringify(extras, null, 4));

  const appearancePath = '/api/application/appearance';
  for (const theme of themeSchema.options) {
    const current = appearanceStatusSchema.parse(await page.request.get(appearancePath).then(response => response.json()));
    const response = await page.request.put(appearancePath, { headers, data: { revision: current.revision, settings: { ...current.settings, theme } } });
    expect(response.ok(), await response.text()).toBe(true);
    await expect(page.locator('html')).toHaveAttribute('data-theme', theme);
    for (const width of [1280, 801, 800, 390]) {
      await page.setViewportSize({ width, height: 850 });
      await advancedToggle.scrollIntoViewIfNeeded();
      await expect(reasoning).toBeVisible();
      expect(await custom.evaluate(element => {
        const bounds = element.getBoundingClientRect();
        return bounds.left >= 0 && bounds.right <= innerWidth && document.documentElement.scrollWidth <= innerWidth;
      })).toBe(true);
      if (width === 1280 || width === 390) {
        await topP.fill('2');
        await sendTest.click();
        await expect(topP).toHaveAccessibleDescription(/Enter a number from 0 to 1 for top_p\./);
        const sampling = page.getByRole('tabpanel').locator('section')
          .filter({ has: page.getByRole('heading', { name: 'Sampling', exact: true }) });
        await sampling.screenshot({ path: testInfo.outputPath(`number-warning-${theme}-${width}.png`) });
        await topP.fill('');
        await reasoning.scrollIntoViewIfNeeded();
        await page.screenshot({ path: testInfo.outputPath(`controls-${theme}-${width}.png`) });
        await page.getByText('Enter extra fields as a JSON object.', { exact: false }).scrollIntoViewIfNeeded();
        await page.screenshot({ path: testInfo.outputPath(`custom-${theme}-${width}.png`) });
        await custom.fill('{\n    "top_k": 50,\n}');
        await expect(problem).toContainText('Line 2, column 16 · Remove the trailing comma.');
        await problem.scrollIntoViewIfNeeded();
        await page.screenshot({ path: testInfo.outputPath(`error-${theme}-${width}.png`) });
        await custom.fill(JSON.stringify(extras, null, 4));
        await advancedToggle.click();
        await expect(custom).toBeHidden();
        await topP.scrollIntoViewIfNeeded();
        await page.screenshot({ path: testInfo.outputPath(`collapsed-${theme}-${width}.png`) });
        await advancedToggle.click();
      }
    }
  }
});
