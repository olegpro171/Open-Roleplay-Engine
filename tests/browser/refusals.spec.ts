import { test, expect } from '@playwright/test';
import type { ChatSnapshot } from '../../src/shared/contracts';
import { defaultContextPreset } from '../../src/shared/context';
import type { LibrarySnapshot } from '../../src/shared/library';

test('discovers saved refusals, keeps false positives, regenerates without refusal input, and previews suffix deletion on desktop and phone', async ({ page, request }) => {
  test.setTimeout(60_000);
  const session = await request.get('/api/session').then(response => response.json());
  const { endpoint } = await request.get('/__test/endpoint').then(response => response.json());
  await request.post('/__test/mode', { data: { mode: 'normal' } });
  await page.goto('/');
  await page.getByLabel('Owner password').fill('browser-synthetic-password');
  await page.getByRole('button', { name: session.setupRequired ? 'Create owner account' : 'Sign in', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Libraries', exact: true })).toBeVisible();
  const library = () => page.request.get('/api/library').then(response => response.json() as Promise<LibrarySnapshot>);
  const command = async (url: string, data: unknown, method = 'POST') => {
    const response = await page.request.fetch(url, { method, headers: { Origin: 'http://127.0.0.1:4173' }, data });
    expect(response.ok(), await response.text()).toBe(true);
    return response.json();
  };
  const connection = await command('/api/library', { revision: (await library()).revision, kind: 'connections', data: { name: 'Refusal recovery model', model: 'synthetic-summary', endpoint, contextWindow: 100_000, maxOutputTokens: 1_000, customParameters: {} } });
  const preset = await command('/api/library', { revision: (await library()).revision, kind: 'contexts', data: { ...defaultContextPreset, name: 'Refusal recovery context', connectionId: connection.id, minTail: 2, batchSize: 2, promotionGroup: 2, retainedPerLevel: 1 } });
  const chat = await command('/api/chats', { title: 'Saved refusal recovery', targetInputTokens: 500, connectionId: connection.id, promptId: 'default', characterId: null, personaId: null, contextPresetId: preset.id });
  const state = () => page.request.get(`/api/chats/${chat.id}`).then(response => response.json() as Promise<ChatSnapshot>);
  const requests = () => request.get('/__test/requests').then(response => response.json() as Promise<{ body: unknown }[]>);
  await command(`/api/chats/${chat.id}/history`, { revision: (await state()).revision, turns: Array.from({ length: 8 }, (_, index) => ({ user: `Turn ${index + 1}. Mira gives Leon a brass key. ${'The quiet room. '.repeat(14)}`, assistant: `Leon promises to return it. ${'The cellar remains closed. '.repeat(12)}`, complete: true })) }, 'PUT');
  await command(`/api/chats/${chat.id}/context/prepare`, { revision: (await state()).revision, requestId: crypto.randomUUID(), mode: 'step' });
  await expect.poll(async () => (await state()).context.jobs[0]?.status).toBe('succeeded');
  const refusal = "I can't help with this. Please try a different request.";
  const poison = async () => {
    const snapshot = await state(), ref = snapshot.context.selected[0];
    await command(`/api/chats/${chat.id}/context/summaries/${ref.id}`, { revision: snapshot.revision, summaryRevision: ref.revision, text: refusal }, 'PATCH');
  };
  await poison();
  const calls = (await requests()).length;
  await page.getByRole('button', { name: 'Libraries', exact: true }).click();
  await page.getByRole('button', { name: 'Chats', exact: true }).click();
  await page.getByRole('article').filter({ has: page.getByRole('heading', { name: 'Saved refusal recovery', exact: true }) }).click();
  await page.getByRole('button', { name: 'Story', exact: true }).click();
  await expect(page.getByText('1 summary may contain a refusal.', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Review suspected refusals', exact: true }).click();
  const review = page.getByRole('region', { name: 'Suspected refusals', exact: true });
  await review.locator('summary').first().click();
  await expect(review.getByText(refusal, { exact: true })).toBeVisible();
  await review.getByRole('button', { name: 'Keep as is', exact: true }).click();
  await expect(review).toHaveCount(0);
  expect((await requests()).length).toBe(calls);
  // An actual text edit creates a new revision and requires a new decision.
  const kept = await state(), ref = kept.context.selected[0];
  await command(`/api/chats/${chat.id}/context/summaries/${ref.id}`, { revision: kept.revision, summaryRevision: ref.revision, text: 'I cannot summarize this content.' }, 'PATCH');
  await expect(review).toBeVisible();
  await review.locator('summary').first().click();
  await review.getByRole('button', { name: 'Regenerate & repair', exact: true }).click();
  await expect(review.getByText('Marked for regeneration. Open Repair summaries to continue.', { exact: true }).first()).toBeVisible();
  expect((await requests()).length).toBe(calls);
  await page.getByRole('button', { name: 'Repair summaries', exact: true }).click();
  const repair = page.getByRole('dialog', { name: 'Review the proposed replacement' });
  await expect(repair.getByLabel('Proposed summary', { exact: true })).toContainText('The lantern');
  const recoveryRequests = (await requests()).slice(calls);
  expect(recoveryRequests).toHaveLength(1);
  expect(JSON.stringify(recoveryRequests)).not.toContain('I cannot summarize');
  expect(JSON.stringify(recoveryRequests)).not.toContain("I can't help");
  await repair.getByRole('button', { name: 'Approve & Finish', exact: true }).click();
  await expect(repair).toHaveCount(0);
  await expect(review).toHaveCount(0);
  await poison();
  await expect(review).toBeVisible();
  await review.locator('summary').first().click();
  await review.getByRole('button', { name: 'Delete from here onward…', exact: true }).click();
  const deletion = page.getByRole('region', { name: 'Delete memory from this point onward?', exact: true });
  await expect(deletion.getByRole('heading')).toBeFocused();
  await expect(deletion).toContainText('Original turns and historical requests remain saved');
  await review.screenshot({ path: 'test-results/refusals-desktop.png' });
  await page.setViewportSize({ width: 390, height: 844 });
  await deletion.getByRole('button', { name: 'Delete this memory suffix', exact: true }).scrollIntoViewIfNeeded();
  await expect(deletion.getByRole('button', { name: 'Delete this memory suffix', exact: true })).toBeVisible();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: 'test-results/refusals-phone.png' });
  await deletion.getByRole('button', { name: 'Cancel deletion', exact: true }).click();
  expect((await state()).context.selected.length).toBe(1);
  await review.getByRole('button', { name: 'Delete from here onward…', exact: true }).click();
  const beforeDeletion = await state(), callsBeforeDeletion = (await requests()).length;
  await deletion.getByRole('button', { name: 'Delete this memory suffix', exact: true }).click();
  await expect(review).toHaveCount(0);
  expect((await state()).turns).toEqual(beforeDeletion.turns);
  expect((await state()).context.summaries).toEqual([]);
  expect((await requests()).length).toBe(callsBeforeDeletion);
  await page.getByRole('button', { name: 'Prepare chat', exact: true }).click();
  await expect.poll(async () => (await state()).context.jobs[0]?.status).toBe('succeeded');
  expect((await state()).context.selected.length).toBeGreaterThan(0);
});
